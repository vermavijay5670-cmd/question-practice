// Writes src/data/<subject>/counts.js with the number of questions in every chapter bank,
// so the home screens can show counts without downloading the banks themselves.
import fs from 'fs';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
try {
  for (const subject of ['biology', 'physics', 'chemistry']) {
    const { LOADERS } = await server.ssrLoadModule(`/src/data/${subject}/questions.js`);
    const counts = {};
    for (const [id, load] of Object.entries(LOADERS)) {
      const qs = await load();
      if (!Array.isArray(qs)) throw new Error(`${subject}/${id}: bank did not export an array`);
      counts[id] = qs.length;
    }
    const body = Object.entries(counts).map(([id, n]) => `  '${id}': ${n},`).join('\n');
    fs.writeFileSync(
      `src/data/${subject}/counts.js`,
      `// AUTO-GENERATED by scripts/gen-counts.mjs — do not edit by hand.\nexport const QUESTION_COUNTS = {\n${body}\n};\n`
    );
    console.log(`${subject}: ${Object.keys(counts).length} chapters, ${Object.values(counts).reduce((a, b) => a + b, 0)} questions`);
  }
} finally {
  await server.close();
}
